// Emits src/types/api.ts from the backend's Express route files, so the frontend
// calls the paths the API actually exposes instead of copy-pasted strings.
// Response bodies are NOT generated (controllers have no exportable schema);
// they live in src/types/domain.ts.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const backend = join(here, '..', '..', 'backend', 'src')
const out = join(here, '..', 'src', 'types', 'api.ts')
const METHODS = 'get|post|put|patch|delete'

const joinPath = (...parts: string[]) =>
  ('/' + parts.join('/')).replace(/\/+/g, '/').replace(/(.)\/$/, '$1')

const pascal = (path: string) =>
  path
    .split('/')
    .filter(Boolean)
    .map((part) =>
      part.replace(/^:/, '').replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : '')),
    )
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')

/** Split a call's arguments on top-level commas, ignoring strings and nesting. */
const splitArgs = (args: string) => {
  const parts: string[] = []
  let depth = 0
  let quote = ''
  let current = ''
  for (const char of args) {
    if (quote) {
      if (char === quote) quote = ''
    } else if (char === '"' || char === "'" || char === '`') quote = char
    else if (char === '(' || char === '[' || char === '{') depth++
    else if (char === ')' || char === ']' || char === '}') depth--
    else if (char === ',' && depth === 0) {
      parts.push(current)
      current = ''
      continue
    }
    current += char
  }
  if (current.trim()) parts.push(current)
  return parts
}

/** router.<method>("path", middleware, controller) — the controller is the last arg. */
const parseRoutes = (source: string) => {
  const routes: { method: string; route: string; handler: string }[] = []
  for (const match of source.matchAll(new RegExp(`router\\.(${METHODS})\\(`, 'g'))) {
    const bodyStart = match.index + match[0].length
    let depth = 1
    let end = bodyStart
    while (end < source.length && depth > 0) {
      if (source[end] === '(') depth++
      else if (source[end] === ')') depth--
      end++
    }
    const args = splitArgs(source.slice(bodyStart, end - 1))
    const route = args[0]?.trim().match(/^["'`]([^"'`]+)["'`]$/)?.[1]
    const last = args.at(-1)?.trim() ?? ''
    // plain controller, or a wrapper call like asyncRoute(getSettings)
    const handler =
      last.match(/^([A-Za-z_$][\w$]*)$/)?.[1] ??
      last.match(/^[A-Za-z_$][\w$]*\(\s*([A-Za-z_$][\w$]*)/)?.[1]
    if (route && handler) routes.push({ method: match[1] ?? '', route, handler })
  }
  return routes
}

const app = readFileSync(join(backend, 'app.ts'), 'utf8')

// import adminUserRoutes from "./routes/adminUserRoutes.js"
const routers = new Map<string, string>()
for (const [, variable, file] of app.matchAll(/import (\w+) from "\.\/routes\/(\w+)\.js"/g)) {
  if (variable && file) routers.set(variable, file)
}

// app.use("/admin/users", adminUserRoutes) — first mount wins, any other becomes altPath
const mounts = new Map<string, string[]>()
for (const [, prefix, variable] of app.matchAll(/app\.use\("([^"]+)",\s*(\w+)\)/g)) {
  if (prefix && variable) mounts.set(variable, [...(mounts.get(variable) ?? []), prefix])
}

const generated: Record<string, string[]> = {}
let count = 0

for (const [variable, file] of routers) {
  const prefixes = mounts.get(variable) ?? ['/']
  const used = new Set<string>()
  const lines: string[] = []

  for (const { method, route, handler } of parseRoutes(
    readFileSync(join(backend, 'routes', `${file}.ts`), 'utf8'),
  )) {
    const key = used.has(handler)
      ? `${handler}${pascal(route)}${method.charAt(0).toUpperCase()}${method.slice(1)}`
      : handler
    used.add(key)
    const [primary, ...rest] = prefixes
    const altPath = rest[0] ? `, altPath: '${joinPath(rest[0], route)}'` : ''
    lines.push(
      `    ${key}: { method: '${method}', path: '${joinPath(primary ?? '/', route)}'${altPath} },`,
    )
    count++
  }

  if (lines.length) generated[variable] = lines
}

mkdirSync(dirname(out), { recursive: true })
writeFileSync(
  out,
  `// GENERATED by scripts/generate-api-types.ts from ../backend — do not edit.\n` +
    `// Re-run: npm run gen:api\n\n` +
    `export const apiRoutes = {\n` +
    Object.entries(generated)
      .map(([name, lines]) => `  ${name}: {\n${lines.join('\n')}\n  },`)
      .join('\n') +
    `\n} as const\n`,
)

console.log(`wrote ${out} — ${count} endpoints`)
